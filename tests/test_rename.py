"""An install made under the old name (meta) moves to once on `once init`, and nothing is left calling the old code."""
import json

from once import cli, index, paths


def test_init_moves_an_old_meta_install(env, tmp_path, monkeypatch):
    repo, settings = env["repo"], env["settings"]
    old = tmp_path / "old-home"
    rules = old / "memory" / "github.com" / "acme" / "api" / "rules"
    rules.mkdir(parents=True)
    (rules / "use-tox.yaml").write_text(
        "schema: 1\nid: use-tox\nstatus: active\nkind: invariant\nscope: {path_globs: []}\n"
        "rule: {directive: Run tests with tox., rationale: ''}\nprovenance: {source_kind: manual}\n")
    (old / "config.json").write_text(json.dumps({"statusline_wrap": "echo mine"}))
    monkeypatch.setenv("ONCE_OLD_HOME", str(old))
    monkeypatch.setenv("ONCE_HOME", str(tmp_path / "new-home"))

    settings.parent.mkdir(parents=True, exist_ok=True)
    settings.write_text(json.dumps({
        "model": "x",
        "hooks": {"SessionStart": [{"hooks": [{"type": "command", "command": "python -m metaagent.hook claude-code"}]},
                                   {"hooks": [{"type": "command", "command": "someone-else"}]}]},
        "statusLine": {"type": "command", "command": "python -m metaagent.statusline"}}))
    cmds = settings.parent / "commands"
    cmds.mkdir()
    (cmds / "meta-teach.md").write_text("---\n---\nx\n<!-- generated by meta-agent -->\n")
    (cmds / "meta-mine.md").write_text("my own command\n")
    (repo / ".claude" / "rules" / "meta-agent").mkdir(parents=True)
    (repo / ".claude" / "skills" / "meta-agent-deploy").mkdir(parents=True)

    assert cli.main(["init", "--yes"]) == 0
    s = json.loads(settings.read_text())
    flat = json.dumps(s)
    assert "metaagent" not in flat and "once.hook" in flat and "someone-else" in flat and s["model"] == "x"
    assert "once.statusline" in s["statusLine"]["command"]
    assert json.loads((paths.home() / "config.json").read_text())["statusline_wrap"] == "echo mine"
    assert not old.exists() and (paths.home() / "memory").is_dir()
    assert any(r["id"] == "use-tox" for r in index.load("github.com/acme/api")["rules"])
    assert not (cmds / "meta-teach.md").exists() and (cmds / "meta-mine.md").exists() and (cmds / "once-teach.md").exists()
    assert not (repo / ".claude" / "rules" / "meta-agent").exists() and not (repo / ".claude" / "skills" / "meta-agent-deploy").exists()

    # a second run has nothing to move
    from once import migrate
    assert migrate.migrate(repo) == []
