"""Move an install of the tool under its old name, meta (package meta-agent, module metaagent), to once.

Run by `once init`. Idempotent: a second run finds nothing to do. Every step is optional; a failure in one
does not stop the others. Nothing the user wrote is deleted: the data folder is moved, never removed.
"""
import json
import os
import shutil
import subprocess
from pathlib import Path

OLD_HOME = Path.home() / ".meta-agent"
OLD_HOOK_MARK = "metaagent.hook"
OLD_STATUS_MARK = "metaagent.statusline"
OLD_NAME = "meta-agent"


def _old_home() -> Path:
    return Path(os.environ.get("ONCE_OLD_HOME") or OLD_HOME)


def migrate(repo_root: Path | None = None) -> list[str]:
    from . import paths
    from .adapters import antigravity as agy
    from .adapters import claude_code as cc
    done = []

    # 1. data: rules, sessions, settings
    old, new = _old_home(), paths.home()
    if old.is_dir() and old.resolve() != new.resolve():
        if not new.exists():
            shutil.move(str(old), str(new))
            done.append(f"moved your rules and sessions from {old} to {new}")
        else:
            done.append(f"left {old} in place because {new} already exists; delete it once you have checked")

    # 2. Claude Code settings: old hooks out, old status line swapped back to whatever it wrapped
    p = cc.settings_path()
    if p.exists():
        try:
            s = json.loads(p.read_text() or "{}")
            changed = False
            hooks = s.get("hooks") or {}
            for ev in list(hooks):
                keep = [g for g in hooks[ev] if not any(OLD_HOOK_MARK in (h.get("command") or "")
                                                        for h in g.get("hooks", []))]
                if len(keep) != len(hooks[ev]):
                    changed = True
                    hooks[ev] = keep
                if not hooks[ev]:
                    del hooks[ev]
            if "hooks" in s and not hooks:
                s.pop("hooks")
            sl = s.get("statusLine") or {}
            if OLD_STATUS_MARK in (sl.get("command") or ""):
                cfg = {}
                try:
                    cfg = json.loads((paths.home() / "config.json").read_text())
                except Exception:
                    pass
                if cfg.get("statusline_wrap"):
                    s["statusLine"] = {"type": "command", "command": cfg["statusline_wrap"]}
                else:
                    s.pop("statusLine", None)
                changed = True
            if changed:
                p.write_text(json.dumps(s, indent=2) + "\n")
                done.append("removed the old meta hooks from Claude Code")
        except Exception as e:
            done.append(f"could not clean {p}: {e}")

    # 3. old slash commands
    d = cc.commands_dir()
    gone = 0
    for f in d.glob("meta-*.md") if d.is_dir() else []:
        try:
            if "generated by meta" in f.read_text():
                f.unlink()
                gone += 1
        except Exception:
            pass
    if gone:
        done.append(f"removed {gone} old slash commands (/meta-teach and others)")

    # 4. old MCP server
    claude = shutil.which("claude")
    if claude and not os.environ.get("ONCE_CLAUDE_SETTINGS"):
        try:
            r = subprocess.run([claude, "mcp", "remove", "-s", "user", OLD_NAME], capture_output=True, text=True,
                               timeout=20, stdin=subprocess.DEVNULL)
            if r.returncode == 0:
                done.append("removed the old meta-agent MCP server")
        except Exception:
            pass

    # 5. Antigravity: the old hook group
    try:
        ap = agy.settings_path()
        if ap.exists():
            s = json.loads(ap.read_text() or "{}")
            if OLD_NAME in s:
                del s[OLD_NAME]
                ap.write_text(json.dumps(s, indent=2) + "\n")
                done.append("removed the old meta hooks from Antigravity")
    except Exception:
        pass

    # 6. generated files in this repo
    if repo_root:
        root = Path(repo_root)
        n = 0
        od = root / ".claude" / "rules" / OLD_NAME
        if od.is_dir():
            shutil.rmtree(od, ignore_errors=True)
            n += 1
        for sk in (root / ".claude" / "skills").glob(f"{OLD_NAME}-*") if (root / ".claude" / "skills").is_dir() else []:
            shutil.rmtree(sk, ignore_errors=True)
            n += 1
        if n:
            done.append("removed old generated rule and skill files from this repo")

    # 7. menu bar plugin and editor extensions
    from . import ambient
    for md in ambient.menubar_dirs():
        f = md / "meta.1m.sh"
        if f.exists():
            f.unlink()
            done.append("replaced the old menu bar plugin (run  once menubar --install  to add the new one)")
    for ed in (".vscode", ".cursor", ".windsurf"):
        ext = Path.home() / ed / "extensions"
        for old_ext in ext.glob("meta-agent.meta-agent-*") if ext.is_dir() else []:
            shutil.rmtree(old_ext, ignore_errors=True)
            done.append(f"removed the old {ed.strip('.')} extension (run  once editor install  for the new one)")
    return done
